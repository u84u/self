func auditCmd(args []string) error {
	fs := flag.NewFlagSet("self audit", flag.ExitOnError)
	artifact := fs.String("artifact", "", "artifact to audit (required)")
	keys := fs.String("keys", "keys", "directory of customer *.pub keys")
	fs.Parse(args)
	if *artifact == "" {
		return errors.New("audit requires -artifact")
	}
	data, err := os.ReadFile(*artifact)
	if err != nil {
		return err
	}
	issues := 0
	// check each public key's raw bytes
	paths, _ := filepath.Glob(filepath.Join(*keys, "*.pub"))
	for _, path := range paths {
		pub, _ := os.ReadFile(path)
		key, _, _, _, err := ssh.ParseAuthorizedKey(pub)
		if err != nil {
			continue
		}
		if cryptoPub, ok := key.(ssh.CryptoPublicKey); ok {
			raw := cryptoPub.CryptoPublicKey()
			if ed, ok := raw.(ed25519.PublicKey); ok {
				if bytes.Contains(data, ed) {
					fmt.Printf("LEAK: raw public key from %s found in artifact\n", filepath.Base(path))
					issues++
				}
			}
		}
		if bytes.Contains(data, bytes.TrimSpace(pub)) {
			fmt.Printf("LEAK: authorized_keys line from %s found in artifact\n", filepath.Base(path))
			issues++
		}
	}
	if issues == 0 {
		fmt.Println("audit: no obvious key leakage detected")
	} else {
		fmt.Printf("audit: %d issue(s) found\n", issues)
	}
	return nil
}

