func batchCmd(args []string) error {
	fs := flag.NewFlagSet("self batch", flag.ExitOnError)
	targets := fs.String("targets", "", "comma-separated list of targets (required)")
	outDir := fs.String("out-dir", "dist", "output directory")
	defaultKeys := "keys"
	if v := os.Getenv("SELF_KEYS"); v != "" {
		defaultKeys = v
	}
	keys := fs.String("keys", defaultKeys, "directory of customer *.pub keys")
	decoys := fs.Int("decoys", -1, "decoy count (negative = random)")
	fs.Parse(args)
	if *targets == "" {
		return errors.New("batch requires -targets")
	}
	if err := os.MkdirAll(*outDir, 0o755); err != nil {
		return err
	}
	recipients, err := keystore.Load(*keys)
	if err != nil {
		return err
	}
	if *decoys < 0 {
		n, _ := rand.Int(rand.Reader, big.NewInt(25))
		*decoys = 8 + int(n.Int64())
	}
	pad, err := keystore.Decoys(*decoys)
	if err != nil {
		return err
	}
	list := strings.Split(*targets, ",")
	var wg sync.WaitGroup
	for _, t := range list {
		t = strings.TrimSpace(t)
		if t == "" {
			continue
		}
		wg.Add(1)
		go func(target string) {
			defer wg.Done()
			base := filepath.Base(target)
			out := filepath.Join(*outDir, base+".locked")
			platform, err := packer.Platform(target)
			if err != nil {
				fmt.Println("skip", target, err)
				return
			}
			stubData, err := stubs.Lookup(platform)
			if err != nil {
				fmt.Println("skip", target, err)
				return
			}
			sf, _ := os.CreateTemp("", "self-stub-*")
			sf.Write(stubData)
			sf.Close()
			err = packer.Pack(packer.Options{
				Stub:       sf.Name(),
				Target:     target,
				Out:        out,
				Recipients: append(append([]age.Recipient{}, recipients...), pad...),
			})
			os.Remove(sf.Name())
			if err != nil {
				fmt.Println("fail", target, err)
			} else {
				fmt.Println("packed", target, "->", out)
			}
		}(t)
	}
	wg.Wait()
	return nil
}

